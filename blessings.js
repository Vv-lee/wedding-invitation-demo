const blessingStorageKey = 'wedding-blessings-v1';
let blessingAssignments = new Map();
try {
  const saved = JSON.parse(localStorage.getItem(blessingStorageKey) || '[]');
  if (Array.isArray(saved)) blessingAssignments = new Map(saved.filter(entry => Array.isArray(entry) && typeof entry[0] === 'string' && Number.isInteger(entry[1]) && entry[1] >= 0 && entry[1] < blessings.length));
} catch { /* Keep draws in memory if storage is unavailable. */ }
function blessingFor(name) {
  const key = name.normalize('NFKC').trim().replace(/\s+/g, ' ').toLowerCase();
  if (!blessingAssignments.has(key)) {
    const used = new Set(blessingAssignments.values());
    const available = blessings.map((_, index) => index).filter(index => !used.has(index));
    // shortcut: After 100 distinct guests, reuse the pool; global uniqueness needs shared storage.
    const pool = available.length ? available : blessings.map((_, index) => index);
    blessingAssignments.set(key, pool[Math.floor(Math.random() * pool.length)]);
    try { localStorage.setItem(blessingStorageKey, JSON.stringify([...blessingAssignments])); } catch { /* Draw still works in memory. */ }
  }
  return blessings[blessingAssignments.get(key)];
}
function blessingLines(text, measure, maxWidth) {
  const lines = [];
  let line = '';
  for (const character of text) {
    if (line && measure(line + character) > maxWidth) { lines.push(line); line = ''; }
    line += character;
  }
  if (line) lines.push(line);
  return lines;
}
